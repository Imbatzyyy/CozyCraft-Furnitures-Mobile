import assert from 'node:assert/strict'
const {chromium,webkit}=await import(process.env.PLAYWRIGHT_MODULE||'playwright')
for(const engine of [chromium,webkit]) {
 const browser=await engine.launch({headless:true,...(engine===chromium?{channel:'chrome'}:{})})
 for(const [width,height] of [[320,640],[390,844],[768,1024],[844,390]]) {
  const page=await browser.newPage({viewport:{width,height}})
  await page.goto('http://127.0.0.1:5187/?membership&text=extra-large')
  await page.locator('.home-circle').waitFor()
  assert.equal(await page.locator('.cozy-scroll-back').count(),0)
  await page.locator('.home-circle').evaluate(el=>el.scrollTop=650)
  await page.getByRole('button',{name:'Back to previous page'}).waitFor()
  const rect=await page.locator('.cozy-scroll-back').boundingBox()
  assert.ok(rect.x>=0&&rect.y>=0&&rect.y+rect.height<=height+1,JSON.stringify(rect))
  await page.locator('.hc-header button').evaluate(el=>el.addEventListener('click',()=>document.body.dataset.backClicked='yes'))
  await page.getByRole('button',{name:'Back to previous page'}).click()
  assert.equal(await page.locator('body').getAttribute('data-back-clicked'),'yes')
  await page.locator('.home-circle').evaluate(el=>el.scrollTop=0)
  await page.waitForFunction(()=>!document.querySelector('.cozy-scroll-back'))
  await page.locator('.home-circle').evaluate(el=>el.scrollTop=650)
  await page.getByRole('button',{name:'Back to previous page'}).waitFor()
  await page.locator('.hc-header button').evaluate(el=>el.disabled=true)
  await page.waitForFunction(()=>!document.querySelector('.cozy-scroll-back'))
  await page.locator('.hc-header button').evaluate(el=>el.disabled=false)
  await page.getByRole('button',{name:'Back to previous page'}).waitFor()
  await page.locator('.home-circle').evaluate(el=>{
    const dialog=document.createElement('section')
    dialog.id='qa-nested';dialog.setAttribute('role','dialog');dialog.setAttribute('aria-modal','true')
    Object.assign(dialog.style,{position:'fixed',inset:'0',zIndex:'2147483000',background:'white'})
    el.append(dialog)
  })
  await page.waitForFunction(()=>!document.querySelector('.cozy-scroll-back'))
  await page.locator('#qa-nested').evaluate(el=>el.remove())
  await page.getByRole('button',{name:'Back to previous page'}).waitFor()
  await page.locator('.home-circle').evaluate(el=>{const input=document.createElement('input');input.id='qa-input';el.append(input);input.focus({preventScroll:true})})
  await page.waitForFunction(()=>!document.querySelector('.cozy-scroll-back'))
  await page.locator('#qa-input').evaluate(el=>{el.blur();el.remove()})
  await page.getByRole('button',{name:'Back to previous page'}).waitFor()
  if(engine===webkit&&width===390) await page.screenshot({path:'/tmp/cozy-scroll-back.png'})
  await page.close()
 }
 await browser.close()
}
console.log('PASS 8 floating-back layouts: scroll threshold, viewport bounds, existing back callback, return to top, disabled action.')
